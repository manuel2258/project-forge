defmodule ForgeWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :forge

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  # `secure` in production, where docs/deploy.md puts TLS in front: the browser then never sends
  # this cookie over cleartext, whatever a link or a stale bookmark says. Not in dev, which is
  # plain http on loopback and where setting it would simply break login.
  @session_options [
    store: :cookie,
    key: "_forge_key",
    signing_salt: "i+BpcGu5",
    same_site: "Lax",
    secure: Mix.env() == :prod
  ]

  # Workers dial in here. `x_headers` carries the `authorization` header the worker
  # authenticates with; it is not in the URL on purpose. See docs/design/worker-channel.md.
  socket "/worker", ForgeWeb.WorkerSocket,
    websocket: [connect_info: [:x_headers]],
    longpoll: false

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :forge,
    gzip: not code_reloading?,
    only: ForgeWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :forge
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  # A container runtime probes `/health` every few seconds, and a line per probe buries every
  # other request in the log. See `log_level/1`.
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  # Git's smart HTTP is served here rather than from the router: it authenticates with a per-job
  # token over HTTP Basic rather than the session or the API bearer, and its request body is a
  # packfile that must reach `git http-backend` unread. Above the parsers, the session and the
  # method override, all of which are meaningless to git and are surface we do not want.
  plug ForgeWeb.Plugs.GitHttp, at: "/git"

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug ForgeWeb.Router

  @doc """
  The level `Phoenix.Logger` logs a request at: nothing for the liveness probe, `:info` for the
  rest, which is Phoenix's own default. Matched on the whole path, so only the probe itself goes
  quiet — `/health/deep` is a 404 worth seeing.

  `request_path` and not `path_info`: this is asked again for the `Sent 200` line, after the
  router's `forward` has stripped `path_info` down to what lies below the mount point.
  """
  def log_level(%Plug.Conn{request_path: "/health"}), do: false
  def log_level(_conn), do: :info
end
